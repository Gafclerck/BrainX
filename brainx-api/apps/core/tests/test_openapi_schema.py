"""Centralized OpenAPI schema validation (Epic 4, Story 4.1).

Validates the entire OpenAPI 3.0 specification generated by drf-spectacular once
in setUpClass, replacing 36 redundant SchemaGenerator calls across the test suite.
"""

from django.conf import settings
from django.test import SimpleTestCase
from django.urls import reverse
from drf_spectacular.generators import SchemaGenerator


class OpenApiSchemaTests(SimpleTestCase):
    """Single-pass validation of the complete project OpenAPI schema."""

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.schema = SchemaGenerator().get_schema(request=None, public=True)
        cls.paths = cls.schema['paths']
        cls.components = cls.schema['components']['schemas']

    @classmethod
    def named_schema(cls, ref):
        """Resolve a schema $ref (e.g., '#/components/schemas/ContentErrorResponse')."""
        name = ref.rsplit('/', 1)[-1]
        return cls.components[name]

    # --- Core & Global Contracts ---

    def test_schema_metadata_and_structure(self):
        self.assertIn('openapi', self.schema)
        self.assertTrue(self.schema['openapi'].startswith('3.'))
        self.assertIn('info', self.schema)
        self.assertIn('paths', self.schema)
        self.assertIn('components', self.schema)

    def test_error_envelope_schemas_exist_in_components(self):
        self.assertIn('ContentErrorResponse', self.components)
        error_schema = self.components['ContentErrorResponse']
        self.assertEqual(error_schema['type'], 'object')
        self.assertIn('type', error_schema['properties'])
        self.assertIn('title', error_schema['properties'])
        self.assertIn('status', error_schema['properties'])
        self.assertIn('detail', error_schema['properties'])
        self.assertIn('errors', error_schema['properties'])

    # --- Users Endpoints ---

    def test_registration_schema(self):
        path = f'{settings.API_PREFIX}/register/'
        self.assertIn(path, self.paths)
        op = self.paths[path]['post']
        # Request body
        content = op['requestBody']['content']['application/json']
        req_schema = self.named_schema(content['schema']['$ref'])
        self.assertEqual(sorted(req_schema['properties']), ['email', 'password'])
        # Responses
        self.assertIn('201', op['responses'])
        self.assertIn('400', op['responses'])

    def test_verification_schema(self):
        verify_path = f'{settings.API_PREFIX}/verify-email/'
        self.assertIn(verify_path, self.paths)
        verify_op = self.paths[verify_path]['post']
        self.assertIn('200', verify_op['responses'])
        self.assertIn('400', verify_op['responses'])

        me_path = f'{settings.API_PREFIX}/me/'
        self.assertIn(me_path, self.paths)
        me_op = self.paths[me_path]['get']
        self.assertIn('200', me_op['responses'])
        self.assertIn('401', me_op['responses'])

